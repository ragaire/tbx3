#!/usr/bin/env python3
"""Refresh the site's generated data files. Standard library only.

  python3 tools/update.py steam
      Re-reads your public Steam profile into steam.js (name, avatar, member since).

  python3 tools/update.py spotify --client-id YOUR_CLIENT_ID [--range long_term]
      Logs in to Spotify in your browser, then writes your top tracks, top artists
      and the albums they come from into music.spotify.js.
      Ranges: short_term (~4 weeks), medium_term (~6 months), long_term (~1 year).

Spotify setup (once): https://developer.spotify.com/dashboard -> Create app,
add the redirect URI  http://127.0.0.1:8888/callback  and tick "Web API".
No client secret is needed (this uses the PKCE login).
"""
import argparse
import base64
import datetime
import hashlib
import http.server
import json
import pathlib
import secrets
import sys
import urllib.error
import urllib.parse
import urllib.request
import webbrowser
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_STEAM = "https://steamcommunity.com/id/ronnyronan/"
REDIRECT = "http://127.0.0.1:8888/callback"
UA = {"User-Agent": "personal-site-updater/1.0"}


def write_js(filename, var, data, note):
    stamp = datetime.date.today().isoformat()
    body = json.dumps(data, indent=2, ensure_ascii=False)
    (ROOT / filename).write_text(
        f"// Generated by tools/update.py {note} on {stamp}. Don't edit; rerun the script.\n"
        f"window.{var} = {body};\n",
        encoding="utf-8",
    )
    print(f"Wrote {filename}")


def get(url, headers=None):
    req = urllib.request.Request(url, headers={**UA, **(headers or {})})
    with urllib.request.urlopen(req, timeout=20) as res:
        return res.read()


# ---------------------------------------------------------------- Steam

def steam(args):
    url = args.url.rstrip("/") + "/"
    root = ET.fromstring(get(url + "?xml=1"))
    if root.find("error") is not None:
        sys.exit(f"Steam said: {root.findtext('error')}")
    text = lambda tag: (root.findtext(tag) or "").strip()
    data = {
        "name": text("steamID"),
        "steamID64": text("steamID64"),
        "avatar": text("avatarFull"),
        "memberSince": text("memberSince"),
        "url": url,
    }
    write_js("steam.js", "STEAM", data, "steam")


# ---------------------------------------------------------------- Spotify

def spotify_login(client_id):
    verifier = secrets.token_urlsafe(64)
    challenge = base64.urlsafe_b64encode(hashlib.sha256(verifier.encode()).digest()).rstrip(b"=").decode()
    state = secrets.token_urlsafe(16)
    auth_url = "https://accounts.spotify.com/authorize?" + urllib.parse.urlencode({
        "client_id": client_id,
        "response_type": "code",
        "redirect_uri": REDIRECT,
        "code_challenge_method": "S256",
        "code_challenge": challenge,
        "scope": "user-top-read",
        "state": state,
    })

    result = {}

    class Callback(http.server.BaseHTTPRequestHandler):
        def do_GET(self):
            parsed = urllib.parse.urlparse(self.path)
            if parsed.path != "/callback":
                self.send_response(404)
                self.end_headers()
                return
            result.update({k: v[0] for k, v in urllib.parse.parse_qs(parsed.query).items()})
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.end_headers()
            self.wfile.write(b"<body style='background:#161616;color:#ffdfc4;font:16px Arial;padding:40px'>"
                             b"Done. Close this tab and go back to the terminal.</body>")

        def log_message(self, *a):
            pass

    server = http.server.HTTPServer(("127.0.0.1", 8888), Callback)
    print("Opening the Spotify login in your browser. If nothing opens, visit:\n" + auth_url)
    webbrowser.open(auth_url)
    while "code" not in result and "error" not in result:
        server.handle_request()
    server.server_close()

    if "error" in result:
        sys.exit(f"Spotify login failed: {result['error']}")
    if result.get("state") != state:
        sys.exit("Spotify login failed: state mismatch, try again.")

    body = urllib.parse.urlencode({
        "grant_type": "authorization_code",
        "code": result["code"],
        "redirect_uri": REDIRECT,
        "client_id": client_id,
        "code_verifier": verifier,
    }).encode()
    req = urllib.request.Request("https://accounts.spotify.com/api/token", data=body,
                                 headers={**UA, "Content-Type": "application/x-www-form-urlencoded"})
    with urllib.request.urlopen(req, timeout=20) as res:
        return json.load(res)["access_token"]


def biggest_image(images):
    images = sorted(images or [], key=lambda i: i.get("width") or 0, reverse=True)
    return images[0]["url"] if images else None


def spotify(args):
    token = spotify_login(args.client_id)
    auth = {"Authorization": f"Bearer {token}"}

    def api(path):
        try:
            return json.loads(get("https://api.spotify.com/v1" + path, auth))
        except urllib.error.HTTPError as e:
            sys.exit(f"Spotify API {path} failed: {e.code} {e.read().decode(errors='replace')[:300]}")

    tracks = api(f"/me/top/tracks?limit=50&time_range={args.range}")["items"]
    artists = api(f"/me/top/artists?limit=20&time_range={args.range}")["items"]

    top_songs = [{
        "title": t["name"],
        "artist": ", ".join(a["name"] for a in t["artists"]),
        "album": t["album"]["name"],
        "spotify": t["external_urls"]["spotify"],
        "art": biggest_image(t["album"].get("images")),
    } for t in tracks]

    # Spotify has no "top albums" endpoint: rank albums by how many of your top
    # tracks they hold, weighting higher-ranked tracks more. Full albums first.
    scores, albums = {}, {}
    for rank, t in enumerate(tracks):
        al = t["album"]
        scores[al["id"]] = scores.get(al["id"], 0) + (len(tracks) - rank)
        albums[al["id"]] = al
    ranked = sorted(scores, key=scores.get, reverse=True)
    full = [i for i in ranked if albums[i].get("album_type") in ("album", "compilation")]
    rest = [i for i in ranked if i not in full]
    top_albums = [{
        "title": albums[i]["name"],
        "artist": ", ".join(a["name"] for a in albums[i]["artists"]),
        "spotify": albums[i]["external_urls"]["spotify"],
        "art": biggest_image(albums[i].get("images")),
    } for i in (full + rest)[:10]]

    top_artists = [{
        "name": a["name"],
        "spotify": a["external_urls"]["spotify"],
        "art": biggest_image(a.get("images")),
    } for a in artists]

    write_js("music.spotify.js", "SPOTIFY",
             {"range": args.range, "topSongs": top_songs, "topAlbums": top_albums, "topArtists": top_artists},
             "spotify")
    print(f"{len(top_songs)} songs, {len(top_albums)} albums, {len(top_artists)} artists.")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("steam", help="refresh steam.js")
    s.add_argument("--url", default=DEFAULT_STEAM)
    s.set_defaults(fn=steam)
    sp = sub.add_parser("spotify", help="refresh music.spotify.js")
    sp.add_argument("--client-id", required=True)
    sp.add_argument("--range", default="long_term", choices=["short_term", "medium_term", "long_term"])
    sp.set_defaults(fn=spotify)
    args = p.parse_args()
    args.fn(args)


if __name__ == "__main__":
    main()
